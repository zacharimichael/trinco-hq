// Copies researched state files into the app and rebuilds the index.
// Usage: npm run sync-states [-- /path/to/state-rules]
import { copyFileSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const from = process.argv[2] ?? "/mnt/project-files/state-rules";
const to = new URL("../src/data/states/", import.meta.url).pathname;

const ok = [];
for (const f of readdirSync(from).filter((f) => /^[A-Z]{2}\.json$/.test(f))) {
  try {
    const s = JSON.parse(readFileSync(join(from, f), "utf8"));
    if (s.state !== f.slice(0, 2) || !Array.isArray(s.sections)) throw new Error("missing state or sections");
    copyFileSync(join(from, f), join(to, f));
  } catch (e) {
    console.warn(`Skipped ${f}: ${e.message}`);
  }
}
for (const f of readdirSync(to).filter((f) => /^[A-Z]{2}\.json$/.test(f)).sort()) ok.push(f.slice(0, 2));

writeFileSync(
  join(to, "index.ts"),
  `// Generated by scripts/sync-states.mjs. Do not edit.\n` +
    ok.map((c) => `import ${c} from "./${c}.json";`).join("\n") +
    `\n\nexport const STATE_FILES: Record<string, unknown> = { ${ok.join(", ")} };\n`,
);
console.log(`${ok.length} states: ${ok.join(" ")}`);
